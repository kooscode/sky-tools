    static const size_t HAT_COUNT = sizeof(HAT_DATABASE) / sizeof(HAT_DATABASE[0]);

    const HatInfo* hatDB::getHatList()
    {
        return HAT_DATABASE;
    }

    size_t hatDB::getHatCount()
    {
        return HAT_COUNT;
    }

    const HatInfo* hatDB::getHatById(uint16_t hatId)
    {
        for (size_t i = 0; i < HAT_COUNT; i++)
        {
            if (HAT_DATABASE[i].id == hatId)
                return &HAT_DATABASE[i];
        }
        return nullptr;
    }

    const char* hatDB::getHatName(uint16_t hatId)
    {
        const HatInfo* hat = getHatById(hatId);
        return hat ? hat->name : "Unknown";
    }

    const HatInfo* hatDB::findHatByName(const std::string& name)
    {
        // Case-insensitive search
        std::string lowerName = name;
        std::transform(lowerName.begin(), lowerName.end(), lowerName.begin(),
            [](unsigned char c) { return std::tolower(c); });

        for (size_t i = 0; i < HAT_COUNT; i++)
        {
            std::string hatName = HAT_DATABASE[i].name;
            std::transform(hatName.begin(), hatName.end(), hatName.begin(),
                [](unsigned char c) { return std::tolower(c); });

            if (hatName == lowerName)
                return &HAT_DATABASE[i];
        }
        return nullptr;
    }
